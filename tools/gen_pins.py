#!/usr/bin/env python3
"""Generate firmware/include/pins.h and docs/PINMAP.md from the KiCad board netlists.

The schematic/board is the source of truth for every pin. Re-run after any
hardware change:  python3 tools/gen_pins.py
"""
import os, re, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
BASE = os.path.join(ROOT, "SignalScout_Base", "SignalScout_Base.kicad_pcb")
SLED = os.path.join(ROOT, "SignalScout_Sled.kicad_pcb")

# ESP32-S3-WROOM-1 module pad -> GPIO (Espressif datasheet v1.4, table 3).
WROOM = {4: 4, 5: 5, 6: 6, 7: 7, 8: 15, 9: 16, 10: 17, 11: 18, 12: 8, 13: 19, 14: 20, 15: 3, 16: 46, 17: 9, 18: 10,
         19: 11, 20: 12, 21: 13, 22: 14, 23: 21, 24: 47, 25: 48, 26: 45, 27: 0, 28: 35, 29: 36, 30: 37, 31: 38,
         32: 39, 33: 40, 34: 41, 35: 42, 36: 44, 37: 43, 38: 2, 39: 1}
STRAPPING = {0: "boot mode", 3: "JTAG select", 45: "VDD_SPI voltage", 46: "boot mode / ROM log"}
# AW9523B QFN-24 pad -> port bit (datasheet pin list; matches the schematic symbol).
AW = {1: "P1_0", 2: "P1_1", 3: "P1_2", 4: "P1_3", 5: "P0_0", 6: "P0_1", 7: "P0_2", 8: "P0_3", 10: "P0_4", 11: "P0_5",
      12: "P0_6", 13: "P0_7", 14: "P1_4", 15: "P1_5", 16: "P1_6", 17: "P1_7"}
# Arduino UNO header pad -> name, in the footprint's pad order (power header 1-8, analog 9-14, digital 15-32).
UNO = {**{9 + i: f"A{i}" for i in range(6)}, **{15 + i: f"D{i}" for i in range(14)}, 2: "IOREF", 4: "3V3", 5: "5V", 6: "GND", 7: "GND", 29: "GND"}


def footprints(path):
    """Yield (reference, value, {pad: net}) for every footprint in a .kicad_pcb."""
    t = open(path, encoding="utf-8").read()
    i = 0
    while True:
        i = t.find("(footprint ", i)
        if i < 0:
            return
        depth, j = 0, i
        while True:
            c = t[j]
            if c == '"':
                j = t.index('"', j + 1)
                while t[j - 1] == "\\":
                    j = t.index('"', j + 1)
            elif c == "(":
                depth += 1
            elif c == ")":
                depth -= 1
                if depth == 0:
                    break
            j += 1
        blk = t[i:j + 1]
        i = j + 1
        ref = re.search(r'\(property "Reference" "([^"]*)"', blk)
        val = re.search(r'\(property "Value" "([^"]*)"', blk)
        pads = {}
        for m in re.finditer(r'\(pad "([^"]+)"', blk):
            seg = blk[m.start():blk.find("(pad ", m.end()) if blk.find("(pad ", m.end()) > 0 else len(blk)]
            n = re.search(r'\(net\s+(?:\d+\s+)?"([^"]*)"\)', seg)
            if n and m.group(1) not in pads:
                pads[m.group(1)] = n.group(1)
        yield (ref.group(1) if ref else "?", val.group(1) if val else "", pads)


def find(path, pred):
    for ref, val, pads in footprints(path):
        if pred(ref, val):
            return ref, val, pads
    sys.exit(f"part not found in {path}")


def main():
    _, _, esp = find(BASE, lambda r, v: "ESP32-S3" in v)
    _, _, aw = find(BASE, lambda r, v: "AW9523" in v)
    _, _, uno = find(SLED, lambda r, v: "UNO Q" in v)
    gpio = {}
    for pad, net in esp.items():
        if pad.isdigit() and int(pad) in WROOM and net not in ("GND", "+3V3"):
            gpio[net] = WROOM[int(pad)]
    exp = {net: AW[int(pad)] for pad, net in aw.items() if pad.isdigit() and int(pad) in AW}
    sled = {net: UNO[int(pad)] for pad, net in uno.items() if pad.isdigit() and int(pad) in UNO and not UNO[int(pad)] in ("GND", "3V3", "5V", "IOREF")}

    h = ["// GENERATED by tools/gen_pins.py from SignalScout_Base.kicad_pcb - do not edit.", "#pragma once", "",
         "// ESP32-S3-WROOM-1 GPIO numbers, named after the schematic nets."]
    for net, g in sorted(gpio.items(), key=lambda kv: kv[1]):
        name = "PIN_" + re.sub(r"[^A-Z0-9]", "_", net.upper()).replace("USB_D_", "USB_DN" if net.endswith("-") else "USB_DP")
        if net == "USB_D-": name = "PIN_USB_DN"
        if net == "USB_D+": name = "PIN_USB_DP"
        note = f"  // strapping pin: {STRAPPING[g]}" if g in STRAPPING else ""
        h.append(f"#define {name:<18} {g:>2}{note}")
    h += ["", "// AW9523B I/O expander (I2C 0x58). Value = bit index, port 0 = bits 0-7, port 1 = bits 8-15."]
    for net, p in sorted(exp.items(), key=lambda kv: kv[1]):
        bit = int(p[1]) * 8 + int(p[3])
        h.append(f"#define EXP_{re.sub(r'[^A-Z0-9]', '_', net.upper()):<17} {bit:>2}  // {p}")
    open(os.path.join(ROOT, "firmware", "include", "pins.h"), "w").write("\n".join(h) + "\n")

    s = ["// GENERATED by tools/gen_pins.py from SignalScout_Sled.kicad_pcb - do not edit.", "#pragma once", "",
         "// Arduino UNO Q header pins, named after the sled schematic nets."]
    for net, p in sorted(sled.items()):
        s.append(f"#define PIN_{re.sub(r'[^A-Z0-9]', '_', net.upper()):<12} {p}")
    open(os.path.join(ROOT, "sled", "signalscout_sled", "sketch", "sled_pins.h"), "w").write("\n".join(s) + "\n")

    md = ["# Pin map", "", "Generated by `tools/gen_pins.py` from the KiCad boards. Do not edit by hand.", "",
          "## ESP32-S3-WROOM-1 (base board U1)", "", "| Net | Module pad | GPIO | Note |", "|---|---|---|---|"]
    inv = {v: k for k, v in WROOM.items()}
    for net, g in sorted(gpio.items(), key=lambda kv: kv[1]):
        md.append(f"| `{net}` | {inv[g]} | IO{g} | {'Strapping pin: ' + STRAPPING[g] if g in STRAPPING else ''} |")
    md += ["", "## AW9523B I/O expander (base board U4, I2C 0x58)", "", "| Net | Port pin |", "|---|---|"]
    md += [f"| `{net}` | {p} |" for net, p in sorted(exp.items(), key=lambda kv: kv[1])]
    md += ["", "## UNO Q headers (sled A1)", "", "| Net | UNO pin |", "|---|---|"]
    md += [f"| `{net}` | {p} |" for net, p in sorted(sled.items())]
    open(os.path.join(ROOT, "docs", "PINMAP.md"), "w").write("\n".join(md) + "\n")
    readme = os.path.join(ROOT, "README.md")
    t = open(readme, encoding="utf-8").read()
    a, b = "<!-- PINMAP:BEGIN -->", "<!-- PINMAP:END -->"
    if a in t and b in t:  # embed the tables (without the page title) in the README
        t = t[:t.index(a) + len(a)] + "\n" + "\n".join(l.replace("## ", "#### ") for l in md[4:]) + "\n" + t[t.index(b):]
        open(readme, "w", encoding="utf-8").write(t)
    print(f"{len(gpio)} GPIO nets, {len(exp)} expander nets, {len(sled)} sled nets")


if __name__ == "__main__":
    main()
