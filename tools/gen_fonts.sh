# SignalOS fonts -> LVGL C files (needs: npm i -g lv_font_conv).
#   Space Grotesk (OFL)   interface text, headings, the big clock
#   JetBrains Mono (OFL)  numbers and identifiers: dBm, channels, MACs, coordinates
# Font sources and licences: assets/fonts/. Usage: tools/gen_fonts.sh
set -euo pipefail
cd "$(dirname "$0")/.."
F=assets/fonts; OUT=firmware/lib/ss_ui/fonts; mkdir -p "$OUT"
TXT="0x20-0x7E,0xB0,0xB1,0xB7,0x2013,0x2014,0x2022,0x2026,0x2190-0x2193"
gen() { # name ttf size range [extra]
  lv_font_conv --font "$F/$2" -r "$4" --size "$3" --bpp 4 --format lvgl --lv-include lvgl.h \
    --lv-font-name "$1" --no-compress ${5:-} -o "$OUT/$1.c" >/dev/null
}
for s in 12 14 16 20; do gen ss_sans_$s SpaceGrotesk-Medium.ttf $s "$TXT" "--lv-fallback lv_font_montserrat_$s"; done
for s in 24 28 36 48; do gen ss_sans_$s SpaceGrotesk-Bold.ttf $s "$TXT" "--lv-fallback lv_font_montserrat_$s"; done
for s in 12 14 20 28; do gen ss_mono_$s JetBrainsMono-Medium.ttf $s "0x20-0x7E,0xB0,0xB1"; done
gen ss_clock_112 SpaceGrotesk-Light.ttf 112 "0x20,0x2D,0x30-0x3A"
gen ss_clock_64 SpaceGrotesk-Light.ttf 64 "0x20,0x2D,0x30-0x3A"
{ echo "// Generated by tools/gen_fonts.sh"; echo "#pragma once"; echo "#include <lvgl.h>"
  for f in "$OUT"/*.c; do echo "LV_FONT_DECLARE($(basename "$f" .c))"; done; } > "$OUT/fonts.h"
ls -1 "$OUT" | wc -l
